    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        
    String npm = npmField.getText().trim();
    String nama = namaField.getText().trim();
    String email = emailField.getText().trim();
    String hp = hpField.getText().trim();
    String alamat = alamatTextArea.getText().trim();

    String prodi = String.valueOf(prodiComboBox.getSelectedItem());

    // Validasi setiap kolom
    String errorNpm = Validator.npm(npm);
    String errorNama = Validator.nama(nama);
    String errorEmail = Validator.email(email);
    String errorHp = Validator.nomorHp(hp);

    String errorProdi = null;
    if (prodiComboBox.getSelectedIndex() < 0
            || prodi.isBlank()) {
        errorProdi = "Program studi wajib dipilih";
    }

    // Tampilkan pesan dan garis merah
    tandai(npmField, npmPesanLabel, errorNpm);
    tandai(namaField, namaPesanLabel, errorNama);
    tandai(prodiComboBox, prodiPesanLabel, errorProdi);
    tandai(emailField, emailPesanLabel, errorEmail);
    tandai(hpField, hpPesanLabel, errorHp);

    // Hitung jumlah kesalahan
    java.util.List<JComponent> salah = new java.util.ArrayList<>();

    if (errorNpm != null) salah.add(npmField);
    if (errorNama != null) salah.add(namaField);
    if (errorProdi != null) salah.add(prodiComboBox);
    if (errorEmail != null) salah.add(emailField);
    if (errorHp != null) salah.add(hpField);

    if (!alamat.isEmpty() && alamat.length() < 5) {
        // Alamat terlalu pendek, beri peringatan
        JOptionPane.showMessageDialog(
                this,
                "Alamat minimal 5 karakter",
                "Validasi",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (!salah.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                salah.size() + " isian perlu diperbaiki.",
                "Validasi",
                JOptionPane.WARNING_MESSAGE
        );

        salah.get(0).requestFocusInWindow();
        return;
    }

    String jenisAnggota = "";

    if (mahasiswaRadiobutton.isSelected()) {
        jenisAnggota = "Mahasiswa";
    } else if (dosenRadiobutton.isSelected()) {
        jenisAnggota = "Dosen";
    } else if (umumRadioButton.isSelected()) {
        jenisAnggota = "Umum";
    }

    if (jenisAnggota.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Pilih jenis anggota terlebih dahulu!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (!persetujuanCheckBox.isSelected()) {
        JOptionPane.showMessageDialog(
                this,
                "Centang persetujuan terlebih dahulu!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String ringkasan =
            "RINGKASAN PENDAFTARAN ANGGOTA\n\n"
            + "NPM: " + npm + "\n"
            + "Nama: " + nama + "\n"
            + "Program Studi: " + prodi + "\n"
            + "Jenis Anggota: " + jenisAnggota + "\n"
            + "Email: " + email + "\n"
            + "Nomor HP: " + hp + "\n"
            + "Alamat: " + alamat;

    JOptionPane.showMessageDialog(
            this,
            ringkasan,
            "Ringkasan Pendaftaran",
            JOptionPane.INFORMATION_MESSAGE
    );

    }//GEN-LAST:event_daftarButtonActionPerformed

