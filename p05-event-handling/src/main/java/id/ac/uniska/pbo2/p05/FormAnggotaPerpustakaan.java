    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        
String npm = npmField.getText().trim();
String nama = namaField.getText().trim();
String email = emailField.getText().trim();
String hp = hpField.getText().trim();
String alamat = alamatTextArea.getText().trim();

String prodi = String.valueOf(prodiComboBox.getSelectedItem());

String jenisAnggota = "";
if (mahasiswaRadiobutton.isSelected()) {
    jenisAnggota = "Mahasiswa";
} else if (dosenRadiobutton.isSelected()) {
    jenisAnggota = "Dosen";
} else if (umumRadioButton.isSelected()) {
    jenisAnggota = "Umum";
}

// Validasi data wajib
if (npm.isEmpty() || nama.isEmpty()
        || email.isEmpty() || hp.isEmpty()
        || alamat.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Semua kolom wajib diisi!",
        "Validasi",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

if (jenisAnggota.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Pilih jenis anggota terlebih dahulu!",
        "Validasi",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

if (!persetujuanCheckBox.isSelected()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Centang persetujuan terlebih dahulu!",
        "Validasi",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

// Membuat ringkasan pendaftaran
String ringkasan =
    "RINGKASAN PENDAFTARAN ANGGOTA\n\n"
    + "NPM: " + npm + "\n"
    + "Nama: " + nama + "\n"
    + "Program Studi: " + prodi + "\n"
    + "Jenis Anggota: " + jenisAnggota + "\n"
    + "Email: " + email + "\n"
    + "Nomor HP: " + hp + "\n"
    + "Alamat: " + alamat;

javax.swing.JOptionPane.showMessageDialog(
    this,
    ringkasan,
    "Ringkasan Pendaftaran",
    javax.swing.JOptionPane.INFORMATION_MESSAGE
);

    }//GEN-LAST:event_daftarButtonActionPerformed

