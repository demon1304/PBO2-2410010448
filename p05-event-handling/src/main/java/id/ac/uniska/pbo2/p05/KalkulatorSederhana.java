    private void hitung(char operator) {
    try {
        double angka1 = Double.parseDouble(
                angka1Field.getText().trim().replace(",", ".")
        );

        double angka2 = Double.parseDouble(
                angka2Field.getText().trim().replace(",", ".")
        );

        double hasil;

        switch (operator) {
            case '+':
                hasil = angka1 + angka2;
                break;
            case '-':
                hasil = angka1 - angka2;
                break;
            case 'x':
                hasil = angka1 * angka2;
                break;
            case '/':
                if (angka2 == 0) {
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Angka pembagi tidak boleh nol!",
                            "Kesalahan",
                            javax.swing.JOptionPane.WARNING_MESSAGE
                    );
                    return;
                }
                hasil = angka1 / angka2;
                break;
            default:
                return;
        }

        hasilLabel.setText("Hasil: " + rapikan(hasil));

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Masukkan kedua angka dengan benar!",
                "Input tidak valid",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
    }
}

private String rapikan(double angka) {
    if (angka == Math.rint(angka)) {
        return String.format(java.util.Locale.US, "%.0f", angka);
    }

    return String.valueOf(angka);
}
    
    
